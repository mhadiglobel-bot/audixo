import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {fileURLToPath} from 'node:url'
import path from 'node:path'
const dir=path.dirname(fileURLToPath(import.meta.url))
const root=path.resolve(dir,'..')
const read=relative=>readFileSync(path.join(root,relative),'utf8')
const domain=JSON.parse(read('config/audixo-domain.json'))
const origin=domain.canonicalOrigin
assert.equal(origin,'https://audixo.tiers.rest','Unapproved canonical domain: review config before publishing')
assert.equal(domain.hostname,new URL(origin).hostname)
assert.equal(domain.siteName,'AUDIXO')
const vite=read('vite.config.ts'),client=read('src/config/site.ts'),prerender=read('scripts/seo-build.mjs')
assert.ok(vite.includes("import domain from './config/audixo-domain.json'")&&vite.includes('const origin=domain.canonicalOrigin'),'Vite must use shared canonical')
assert.ok(client.includes("import domain from '../../config/audixo-domain.json'")&&client.includes('url:configured'),'Client must use shared canonical')
assert.ok(prerender.includes("readFile('config/audixo-domain.json'")&&prerender.includes('const configured=domain.canonicalOrigin'),'Prerender must use shared canonical')
assert.ok(!vite.includes('env.VERCEL_URL?')&&!vite.includes('env.VERCEL_PROJECT_PRODUCTION_URL?'),'Do not fall back to deployment hosts')
const v=JSON.parse(read('vercel.json'))
const hostRedirect=v.redirects.find(x=>x.has?.some(h=>h.type==='header'&&h.key==='host'&&h.value==='audixo.vercel.app'))
assert.ok(hostRedirect&&hostRedirect.destination===origin+'/:path*'&&hostRedirect.permanent===true,'Legacy Vercel host must 308 redirect to canonical')
const manifest=JSON.parse(read('public/site.webmanifest'))
assert.ok(manifest.name.startsWith('AUDIXO'),'PWA brand identity')
assert.ok(!manifest.shortcuts.some(x=>x.url==='/tools/youtube-to-mp3'),'PWA shortcut must target current route')
assert.equal(read('llms.txt'),read('public/llms.txt'),'llms.txt sources must be synchronized')
assert.ok(read('public/llms.txt').includes(origin+'/features'),'LLM directory wrong production URL')
assert.ok(!read('public/llms.txt').includes('.vercel.app'),'LLM file leaks preview origin')
const sitemap=read('dist/sitemap.xml')
const urls=Array.from(sitemap.matchAll(/<loc>([^<]+)<\/loc>/g),x=>x[1])
assert.ok(urls.length>=10,'Sitemap unexpectedly empty')
assert.equal(new Set(urls).size,urls.length,'Duplicate sitemap URLs')
for(const url of urls){
 assert.ok(url.startsWith(origin+'/'),'Noncanonical sitemap URL: '+url)
 const pathname=new URL(url).pathname
 const file=pathname==='/'?'dist/index.html':('dist'+pathname+'/index.html')
 const html=read(file)
 const can=Array.from(html.matchAll(/<link rel="canonical" href="([^"]+)"/g),x=>x[1])
 const og=Array.from(html.matchAll(/<meta property="og:url" content="([^"]+)"/g),x=>x[1])
 assert.deepEqual(can,[url],'Missing/duplicate canonical '+url)
 assert.deepEqual(og,[url],'Missing/duplicate Open Graph URL '+url)
 assert.ok(!html.includes('audixo.vercel.app'),'Legacy preview hostname leaked into rendered HTML '+url)
 assert.ok(/<meta name="description" content="[^"]+"/.test(html),'Missing meta description '+url)
}
assert.ok(!sitemap.includes('/tools/mashup'),'Retired route in sitemap')
const robots=read('dist/robots.txt')
assert.ok(robots.includes('Sitemap: '+origin+'/sitemap.xml'))
assert.ok(!robots.includes('.vercel.app'))
const home=read('dist/index.html')
const website=home.match(/<script id="site-identity-schema" type="application\/ld\+json">([\s\S]+?)<\/script>/)
assert.ok(website,'No WebSite JSON-LD on homepage')
const entity=JSON.parse(website[1])
assert.equal(entity.name,domain.siteName)
assert.equal(entity.url,origin+'/')
assert.ok(entity.alternateName.includes(domain.hostname))
console.log('SEO DOMAIN CONTRACT PASS: '+urls.length+' canonical pages, one primary domain, stable sitemap, WebSite identity, PWA/LLMs, Vercel host redirect.')

